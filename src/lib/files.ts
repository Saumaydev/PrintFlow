import { createHash } from "node:crypto";

export const MAX_UPLOAD_BYTES = 25 * 1024 * 1024; // 25 MB
export const MAX_PDF_PAGES = 500;

export type FileKind = "pdf" | "image" | "office" | "other";

export const ACCEPTED_EXTENSIONS: Record<string, { kind: FileKind; mime: string; label: string }> = {
  pdf: { kind: "pdf", mime: "application/pdf", label: "PDF document" },
  jpg: { kind: "image", mime: "image/jpeg", label: "JPEG photo" },
  jpeg: { kind: "image", mime: "image/jpeg", label: "JPEG photo" },
  png: { kind: "image", mime: "image/png", label: "PNG image" },
  webp: { kind: "image", mime: "image/webp", label: "WebP image" },
  doc: { kind: "office", mime: "application/msword", label: "Word document" },
  docx: { kind: "office", mime: "application/vnd.openxmlformats-officedocument.wordprocessingml.document", label: "Word document" },
  ppt: { kind: "office", mime: "application/vnd.ms-powerpoint", label: "PowerPoint presentation" },
  pptx: { kind: "office", mime: "application/vnd.openxmlformats-officedocument.presentationml.presentation", label: "PowerPoint presentation" },
  xls: { kind: "office", mime: "application/vnd.ms-excel", label: "Excel spreadsheet" },
  xlsx: { kind: "office", mime: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", label: "Excel spreadsheet" },
  txt: { kind: "office", mime: "text/plain", label: "Plain text" },
};

export const ACCEPTED_SUMMARY = "PDF, JPG, PNG, WebP, DOC, DOCX, PPT, PPTX, XLS, XLSX, TXT · up to 25 MB";

export function fileKind(fileName: string, mime: string): { ext: string; kind: FileKind } | null {
  const ext = (fileName.split(".").pop() ?? "").toLowerCase();
  const byExt = ACCEPTED_EXTENSIONS[ext];
  if (byExt) return { ext, kind: byExt.kind };
  if (mime === "application/pdf") return { ext: "pdf", kind: "pdf" };
  if (mime.startsWith("image/")) return { ext: ext || "img", kind: "image" };
  return null;
}

export function sha256(data: Uint8Array): string {
  return createHash("sha256").update(data).digest("hex");
}

/** Best-effort PDF page count by scanning for /Type /Page objects. */
export function countPdfPages(buf: Uint8Array): number {
  try {
    const text = Buffer.from(buf).toString("latin1");
    const matches = text.match(/\/Type\s*\/Page(?![s])/g);
    if (matches && matches.length > 0) return matches.length;
    const countAttr = text.match(/\/Count\s+(\d+)/);
    if (countAttr) return parseInt(countAttr[1], 10);
    return 1;
  } catch {
    return 1;
  }
}

/** Validates magic bytes loosely; returns an error string or null. */
export function validateMagicBytes(buf: Uint8Array, kind: FileKind): string | null {
  if (buf.length < 8) return "File appears to be empty or corrupt.";
  const head = Buffer.from(buf.subarray(0, 8));
  if (kind === "pdf") {
    if (!head.toString("latin1").startsWith("%PDF")) return "This file does not look like a valid PDF.";
  } else if (kind === "image") {
    const isJpg = head[0] === 0xff && head[1] === 0xd8;
    const isPng = head[0] === 0x89 && head[1] === 0x50;
    const isWebp = head.length >= 8 && head.toString("latin1", 0, 4) === "RIFF";
    if (!isJpg && !isPng && !isWebp) return "This file does not look like a valid image.";
  } else if (kind === "office") {
    const isZip = head[0] === 0x50 && head[1] === 0x4b; // docx/pptx/xlsx are zip containers
    const isOle = head[0] === 0xd0 && head[1] === 0xcf; // legacy doc/ppt/xls
    const isText = kind === "office"; // permissive for txt
    if (!isZip && !isOle && !isText) return "This file does not look like a valid Office document.";
  }
  return null;
}

/** Minimal valid single-page blank PDF, used for test prints. */
export function samplePdf(title = "PrintFlow test page"): Buffer {
  const safe = title.replace(/[()\\]/g, " ");
  const stream = `BT /F1 24 Tf 72 720 Td (${safe}) Tj ET
BT /F1 12 Tf 72 690 Td (If this page came out of your printer, the pipeline works end-to-end.) Tj ET
BT /F1 12 Tf 72 672 Td (Generated by PrintFlow agent simulator.) Tj ET`;
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((obj, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.forEach((o) => {
    pdf += `${String(o).padStart(10, "0")} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return Buffer.from(pdf, "latin1");
}
